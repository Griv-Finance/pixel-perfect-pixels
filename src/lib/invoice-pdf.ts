/** Builds a real, downloadable invoice PDF with pdf-lib. Runs client-side only. */
import { PDFDocument, StandardFonts, rgb, type PDFFont } from "pdf-lib";
import { invoicePaid, invoiceTotals, type Invoice } from "@/lib/demo/invoices";
import { invoiceStatus } from "@/lib/demo/invoices";

const A4: [number, number] = [595.28, 841.89];
const M = 50;

/** Amounts are written as "NGN 26,875.00" — the standard PDF fonts have no ₦ glyph. */
const pdfMoney = (n: number, currency: string) =>
  `${currency} ${n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

export async function buildInvoicePdf(r: Invoice): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`${r.id} — Nova Retail Ltd.`);
  const page = doc.addPage(A4);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const { width, height } = page.getSize();
  let y = height - M;

  const text = (s: string, size = 10, f: PDFFont = font, x = M, color = rgb(0.16, 0.1, 0.06)) => {
    page.drawText(s, { x, y, size, font: f, color });
  };
  const right = (s: string, size = 10, f: PDFFont = font, x = width - M, color = rgb(0.16, 0.1, 0.06)) => {
    const w = f.widthOfTextAtSize(s, size);
    page.drawText(s, { x: x - w, y, size, font: f, color });
  };

  // Header
  text("INVOICE", 22, bold, M, rgb(0.49, 0.41, 0.03));
  right(pdfMoney(invoiceTotals(r).total, r.currency), 22, bold);
  y -= 16;
  text("Nova Retail Ltd. · Lagos, Nigeria", 10);
  right(r.status, 10);
  y -= 10;
  text(`${r.id} · Issued ${r.issue} · Due ${r.due}`, 10);
  y -= 28;

  // Bill to
  text("Billed to", 9, font, M, rgb(0.45, 0.45, 0.45));
  text(r.customer, 11, bold, M, y - 14);
  y -= 36;

  // Line items
  const colX = { desc: M, qty: width - 260, unit: width - 175, amount: width - M };
  text("Description", 9, bold, colX.desc, rgb(0.45, 0.45, 0.45));
  text("Qty", 9, bold, colX.qty, rgb(0.45, 0.45, 0.45));
  text("Unit price", 9, bold, colX.unit - bold.widthOfTextAtSize("Unit price", 9), rgb(0.45, 0.45, 0.45));
  text("Amount", 9, bold, colX.amount - bold.widthOfTextAtSize("Amount", 9), rgb(0.45, 0.45, 0.45));
  y -= 6;
  page.drawLine({ start: { x: M, y }, end: { x: width - M, y }, thickness: 0.7, color: rgb(0.85, 0.82, 0.78) });
  y -= 16;
  for (const item of r.items) {
    text(item.name || "Item", 10);
    text(String(item.qty), 10, font, colX.qty);
    right(pdfMoney(item.price, r.currency), 10, font, colX.unit);
    right(pdfMoney(item.qty * item.price, r.currency), 10);
    y -= 16;
  }
  y -= 8;

  // Totals
  const t = invoiceTotals(r);
  const paid = invoicePaid(r);
  const rows: [string, string, boolean][] = [
    ["Subtotal", pdfMoney(t.subtotal, r.currency), false],
    ...(r.discount > 0 ? ([["Discount", `-${pdfMoney(r.discount, r.currency)}`, false]] as [string, string, boolean][]) : []),
    ...(r.vat ? ([["VAT (7.5%)", pdfMoney(t.tax, r.currency), false]] as [string, string, boolean][]) : []),
    ["Total", pdfMoney(t.total, r.currency), true],
    ["Amount paid", pdfMoney(paid, r.currency), false],
    ["Amount remaining", pdfMoney(t.total - paid, r.currency), true],
  ];
  for (const [label, value, strong] of rows) {
    text(label, strong ? 10 : 9.5, strong ? bold : font, width - 200);
    right(value, strong ? 10 : 9.5, strong ? bold : font);
    y -= strong ? 17 : 14;
  }
  y -= 10;

  // Notes
  if (r.notes) {
    text(r.notes, 9.5);
    y -= 14;
  }
  text(r.instructions, 8.5, font, M, rgb(0.45, 0.45, 0.45));
  y -= 24;
  text("Sample invoice generated by the Griv demo — no real money moved.", 8, font, M, rgb(0.55, 0.55, 0.55));

  return doc.save();
}

/** Generates the PDF and triggers a browser download. */
export async function downloadInvoicePdf(r: Invoice) {
  const bytes = await buildInvoicePdf(r);
  const blob = new Blob([bytes as BlobPart], { type: "application/pdf" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${r.id}-${invoiceStatus(r).toLowerCase().replace(/\s+/g, "-")}.pdf`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 30_000);
}
